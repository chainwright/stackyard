// scripts/pick-deck-images.ts
// Pick one public-domain image per ready-made deck via the Openverse MCP
// server's core tools (mcp/openverse) and write src/shared/readyMadeImages.ts
// with each image inlined as a size-capped data URI plus its real credit line
// (licence + creator + source) — TASK-23 d.
//
//   node --import tsx/esm scripts/pick-deck-images.ts
//
// This is the networked path. In an offline sandbox the Openverse API is
// unreachable, so the script reports that and leaves the committed offline-safe
// fallback images (drawn for Stackyard, CC0) in place rather than overwriting
// them with nothing. Run it on a networked machine to replace them with live
// Openverse picks.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { searchImages, fetchImageAsDataUri } from "../mcp/openverse/openverse.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "shared", "readyMadeImages.ts");

const QUERIES: Record<string, string> = {
  vikings: "viking longship",
  "times-tables": "abacus",
  "irish-words": "Cliffs of Moher",
};

const MAX_KB = 40;

async function pickOne(deckKey: string, query: string): Promise<{
  dataUri: string;
  creditLicense: string;
  creditCreator: string;
  creditSource: string;
} | null> {
  // Prefer public-domain mark, fall back to CC0.
  for (const license of ["pdm", "cc0"] as const) {
    const results = await searchImages(query, license, 10).catch(() => []);
    for (const r of results) {
      // Openverse's own thumbnail proxy (api.openverse.org/.../thumb/) is on the
      // allowlist even when the original sits on Flickr etc., so try it first.
      const candidates = [r.thumbnail, r.url].filter((u) => typeof u === "string" && u.length > 0);
      for (const imgUrl of candidates) {
      try {
        const dataUri = await fetchImageAsDataUri(imgUrl, MAX_KB);
        return {
          dataUri,
          creditLicense: r.license.toUpperCase(),
          creditCreator: r.creator,
          creditSource: r.source || r.url,
        };
      } catch {
        // off-list / over-cap / timeout — try the next candidate / result
      }
      }
    }
  }
  return null;
}

async function main(): Promise<void> {
  const picks: Record<string, Awaited<ReturnType<typeof pickOne>>> = {};
  let anyLive = false;
  for (const [deckKey, query] of Object.entries(QUERIES)) {
    try {
      const pick = await pickOne(deckKey, query);
      picks[deckKey] = pick;
      if (pick) anyLive = true;
      console.log(`${deckKey}: ${pick ? "picked a live image" : "no usable live image"}`);
    } catch (err) {
      console.log(`${deckKey}: live search failed (${err instanceof Error ? err.message : err})`);
      picks[deckKey] = null;
    }
  }

  if (!anyLive) {
    console.warn(
      "pick-deck-images: no live images (Openverse unreachable?). " +
        "Leaving the committed offline-safe images in place.",
    );
    return;
  }

  // Build the data module from the live picks (only overwrite when we have
  // live images, so an offline run never wipes the fallback).
  const entries = Object.entries(picks)
    .filter((e): e is [string, NonNullable<(typeof picks)[string]>] => e[1] !== null)
    .map(([key, p]) => `  ${JSON.stringify(key)}: {
    dataUri: ${JSON.stringify(p.dataUri)},
    // A real Openverse pick: label it "Image" and keep its true source URL
    // (TASK-25 b — a credit that names a source must carry a real one).
    creditKind: "image",
    creditLicense: ${JSON.stringify(p.creditLicense)},
    creditCreator: ${JSON.stringify(p.creditCreator)},
    creditSource: ${JSON.stringify(p.creditSource)},
  }`)
    .join(",\n");

  const file = `// src/shared/readyMadeImages.ts
// GENERATED by scripts/pick-deck-images.ts from live Openverse picks (TASK-23 d).
import type { DeckImage } from "./deckImageTypes.js";

export const READY_MADE_IMAGES: Record<string, DeckImage> = {
${entries}
};
`;
  writeFileSync(OUT, file, "utf8");
  console.log(`pick-deck-images: wrote ${OUT} with ${Object.values(picks).filter(Boolean).length} live image(s).`);
}

main().catch((err) => {
  console.error("pick-deck-images:", err instanceof Error ? err.message : err);
  process.exit(1);
});
